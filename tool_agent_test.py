# Cache: artifact_type -> fixture path (generated once, reused)
_fixture_cache: dict[str, str] = {}


def _ensure_fixtures(fixture_dir: str) -> None:
    """Generate all known fixture files in fixture_dir."""
    os.makedirs(fixture_dir, exist_ok=True)
    for artifact, (ext, content) in _FIXTURE_CONTENT.items():
        if artifact in _fixture_cache:
            continue
        path = os.path.join(fixture_dir, f"sample_{artifact}{ext}")
        if not os.path.exists(path) and content:
            with open(path, "w", encoding="utf-8") as f:
                f.write(content)
        _fixture_cache[artifact] = path


def _fixture_for_artifact(artifact_type: str) -> str | None:
    """Return the fixture path for an artifact type, or None."""
    return _fixture_cache.get(artifact_type)


def _resolve_param_fixtures(leaf: dict) -> dict[str, str]:
    """Resolve a fixture path for each file-type parameter in a leaf spec.

    Returns {param_key: fixture_path} for parameters that have an
    artifact_type with a known fixture. Parameters without artifacts
    (integer flags, boolean switches) are skipped.
    """
    result = {}
    inputs = leaf.get("inputs") or {}
    for key, meta in inputs.items():
        if not isinstance(meta, dict):
            continue
        artifact = meta.get("artifact_type") or meta.get("artifact")
        if not artifact or artifact == "directory":
            continue
        path = _fixture_for_artifact(artifact)
        if path and os.path.exists(path):
            result[key] = path
    return result


def _build_subcommand_prompt(fn_name: str, tool_name: str,
                             param_fixtures: dict[str, str],
                             out_path: str, out_param: str | None,
                             sub: str = "", pattern_file: str = "") -> str:
    """Build a task prompt that tells the LLM exactly which fixture to use
    for each parameter, instead of giving it a single file for everything."""
    lines = [f"Call the function {fn_name} (NOT {tool_name} directly)."]
    # List each parameter with its fixture path
    for param_key, fixture_path in sorted(param_fixtures.items()):
        artifact = ""
        # Try to find the artifact type from the fixture filename
        for atype, (ext, _) in _FIXTURE_CONTENT.items():
            if fixture_path.endswith(f"_{atype}{ext}"):
                artifact = f" ({atype})"
                break
        lines.append(f"  - Use '{fixture_path}' as the '{param_key}' parameter{artifact}.")
    # Output parameter
    if out_param:
        lines.append(f"  - Write the output to '{out_path}' as the '{out_param}' parameter.")
    # Subcommand-specific constraints
    if sub == "split":
        lines.append(f"  - The function requires at least one pattern file -- "
                     f"use '{pattern_file}' as the 'file' parameter.")
    if sub == "pipe":
        lines.append('  - The --exec parameter MUST contain "{}" which is replaced '
                     'by the FIFO path. Example: --exec "cat {}".')
    lines.append("After running, the output must exist (if output param was provided) "
                 "or report what it printed (if stdout).")
    return "\n".join(lines)


def _build_nonsubcommand_prompt(tool_name: str, param_fixtures: dict[str, str],
                                out_path: str, out_param: str | None) -> str:
    """Build a task prompt for non-subcommand tools with per-param fixtures."""
    lines = [f"Call the {tool_name} tool."]
    for param_key, fixture_path in sorted(param_fixtures.items()):
        lines.append(f"  - Use '{fixture_path}' as the '{param_key}' parameter.")
    if out_param:
        lines.append(f"  - Write the output to '{out_path}' as the '{out_param}' parameter.")
    lines.append("Aim for exit code 0. Report what it prints if no output file.")
    return "\n".join(lines)


def load_tools(path: str) -> list[dict]:
    with open(path, "r", encoding="utf-8") as f:
        data = yaml.safe_load(f) or {}
    tools = data.get("tools", [])
    return [t for t in tools if isinstance(t, dict) and t.get("name")]


# tokens that indicate a broken/mis-parsed schema. `{{var}}` template
# variables are LEGAL (command placeholders) -- we strip them before checking,
# and only flag real pollution: ANSI escapes, argparse choices `{a,b}` used as
# a name, `[OPTIONS]/[ARGS]` usage text, ellipsis pseudo-tokens.
_TEMPLATE_VAR = re.compile(r"\{\{[a-zA-Z_][a-zA-Z0-9_]*\}\}")
# capture the variable NAME so we can cross-check it against the input schema
_TEMPLATE_VAR_NAME = re.compile(r"\{\{([a-zA-Z_][a-zA-Z0-9_]*)\}\}")
_POLLUTION = re.compile(r"\x1b\[|\.\.\.|\[OPTIONS\]|\[ARGS\]|\bCOMMAND\b|^\.$")
# argparse choices leaked as a parameter key: `{init,check,...}` (not {{var}})
_CHOICES_KEY = re.compile(r"\{[a-zA-Z0-9_,\-\s]+\}")


def _clean_template(command: str) -> str:
    """Replace legal {{var}} placeholders so they don't look like pollution."""
    return _TEMPLATE_VAR.sub("PLACEHOLDER", command)


def validate_tool_schema(tool: dict) -> str:
    """Return '' if the tool's schema is clean enough to give an LLM, else a
    reason (SCHEMA_INVALID / NO_CMD / SUBCOMMAND_INCOMPLETE / R_PACKAGE)."""
    name = tool.get("name", "")
    cmd = tool.get("command") or ""
    as_ = tool.get("arg_style") or "cli"
    inputs = tool.get("inputs") or {}
    # broken command template: check after masking legal {{var}} placeholders
    if _POLLUTION.search(_clean_template(cmd)):
        return f"SCHEMA_INVALID: command polluted ({cmd[:40]})"
    # broken input names: {{var}} is never a legal input KEY; choices `{a,b}`
    # as a key is pollution from argparse subparsers
    for k in inputs.keys():
        if _POLLUTION.search(k) or _TEMPLATE_VAR.search(k) or _CHOICES_KEY.search(k):
            return f"SCHEMA_INVALID: input name polluted ({k!r})"
    if not cmd.strip():
        return "NO_CMD"
    # template variable <-> input schema consistency: every {{var}} in the
    # command must have a matching input OR declared resource (resources are
    # injected by the runner, not LLM args -- kaptain's {{db}} is a KMA
    # database path), or the rendered argv is undefined.
    vars_used = _TEMPLATE_VAR_NAME.findall(cmd)
    declared_names = set(inputs.keys()) | set((tool.get("resources") or {}).keys())
    unknown = [v for v in vars_used if v not in declared_names]
    if unknown:
        return f"SCHEMA_INVALID: unknown template variable {sorted(set(unknown))} (command {cmd[:60]})"
    # R package / python_import without -m: not directly callable as a command
    if as_ == "python" and not (tool.get("callable_via") or "").startswith("python -m "):
        return "R_PACKAGE_OR_IMPORT"
    if as_ == "subcommand" and not tool.get("subcommand_discovery_complete"):
        return "SUBCOMMAND_INCOMPLETE"
    return ""


def to_function_schemas(tool: dict) -> tuple[list[dict], dict]:
    """Build OpenAI function schema(s) for a tool.

    For subcommand CLIs we expand each subcommand into its OWN function so the
    agent picks `bqtools_encode(input, output)` instead of guessing a
    `subcommand` argument. Returns (schemas, fnmap) where fnmap maps the
    function name -> the EXACT leaf ToolSpec to execute -- make_leaf_spec is
    the single source of truth, so the spec the LLM was shown and the spec
    handed to run_tool_spec are the SAME object (never a base-tool re-parse).
    """
    fnmap: dict = {}
    if (tool.get("arg_style") == "subcommand") and tool.get("subcommand_details"):
        out = []
        for sub, detail in (tool.get("subcommand_details") or {}).items():
            # P0: build the leaf spec FIRST (make_leaf_spec is the SINGLE
            # source of truth for a subcommand's inputs -- positional metadata,
            # flag spelling, required semantics, outputs contract) and derive
            # the function schema from ITS `inputs`. Deriving props straight
            # from `subcommand_details[sub].params` re-infers the contract and
            # can drift (e.g. a positional marked required by make_leaf_spec
            # but optional here -> the LLM schema and the validator disagree).
            leaf = make_leaf_spec(tool, sub)
            props = {}
            required = []
            for key, meta in (leaf.get("inputs") or {}).items():
                props[key] = function_property(meta)
                # ONLY an explicit `required: true` (make_leaf_spec forces it
                # for positionals) makes a param required. A flag with no
                # required marker is OPTIONAL -- forcing every param required
                # would hand the LLM a fake schema (e.g. kaptain with all 15
                # flags required -> LLM fills garbage -> CLI error).
                if (meta or {}).get("required") is True:
                    required.append(key)
            fname = f"{tool['name']}_{sub.replace('-', '_')}"
            params_schema = {"type": "object", "properties": props, "required": required}
            # conditional required: at least one param from each group must be
            # provided (e.g. split needs --file OR --sfile OR --xfile). Emitted
            # as JSON Schema ``anyOf`` so the LLM sees the constraint.
            ao = function_anyof(leaf)
            if ao:
                params_schema["anyOf"] = [
                    {"required": grp} for grp in ao if grp
                ]
            out.append({"type": "function", "function": {
                "name": fname,
                "description": _function_description(leaf),
                "parameters": params_schema,
            }})
            fnmap[fname] = leaf
        return out, fnmap
    # non-subcommand: single function
    props = {}
    required = []
    for name, meta in (tool.get("inputs") or {}).items():
        props[name] = function_property(meta)
        # ONLY an explicit `required: true` is required. Auto-discovery cannot
        # reliably know which flags are mandatory, so defaulting to optional is
        # the honest schema (a guessed-required list is worse: the LLM invents
        # values for flags the tool doesn't need).
        if (meta or {}).get("required") is True:
            required.append(name)
    fn = {"type": "function", "function": {
        "name": tool["name"],
        "description": _function_description(tool),
        "parameters": {"type": "object", "properties": props, "required": required},
    }}
    # execution infrastructure (install/venv/command) is NOT tool-call semantics
    # for the LLM; keep only arg_style as a hint.
    if tool.get("arg_style"):
        fn["function"]["arg_style"] = tool["arg_style"]
    fnmap[tool["name"]] = tool
    return [fn], fnmap


def _function_description(tool: dict) -> str:
    """Tool description PLUS the runtime-resource contract, the output
    contract, and any conditional-required constraints, so the LLM knows
    (a) a database/index path is PRECONFIGURED -- never guessed, never an
    argument it must invent -- (b) what the tool produces and where
    (output_dir -> directory), and (c) which parameter groups must be
    provided together."""
    desc = (tool.get("description") or "")
    resources = tool.get("resources") or {}
    if resources:
        names = ", ".join(sorted(resources))
        desc = (desc.strip() + " "
                + f"Runtime resources are preconfigured and must NOT be passed "
                  f"as arguments: {names}.")
    # conditional required constraint hint
    ao = (tool.get("constraints") or {}).get("any_of") or []
    if ao:
        groups = " OR ".join(", ".join(g) for g in ao if g)
        desc = (desc.strip() + " "
                + f"Requires at least one of: {groups}.").strip()
    # exec template constraint: the --exec string MUST contain "{}" which is
    # replaced by the FIFO pipe path. Without it, the CLI rejects the call.
    exec_constraint = (tool.get("constraints") or {}).get("exec_template") or {}
    if exec_constraint.get("contains") == "{}":
        desc = (desc.strip() + " "
                + 'The --exec parameter MUST contain "{}" which is replaced '
                  'by the FIFO path. Example: --exec "cat {}"').strip()
    # artifact type hints: surface what data format each file parameter expects
    # so the LLM doesn't feed FASTA to a Hi-C tool or .cool to a FASTA tool.
    inputs = tool.get("inputs") or {}
    artifact_hints = []
    for key, meta in inputs.items():
        if not isinstance(meta, dict):
            continue
        artifact = meta.get("artifact")
        if artifact and artifact != "directory":
            exts = (meta.get("artifact_info") or {}).get("extensions") or []
            ext_str = "/".join(exts[:3]) if exts else artifact
            artifact_hints.append(f"{key} expects {ext_str}")
    if artifact_hints:
        desc = (desc.strip() + " "
                + "Input formats: " + "; ".join(artifact_hints) + ".").strip()
    outs = tool.get("outputs") or {}
    if isinstance(outs, dict) and outs:
        bits = []
        for name, meta in outs.items():
            if name == "stdout":
                bits.append("stdout (console output)")
                continue
            kind = (meta or {}).get("type", "file") if isinstance(meta, dict) else "file"
            bits.append(f"{name} ({kind})")
        if bits:
            desc = (desc.strip() + " " + f"Produces: {', '.join(bits)}.").strip()
    return desc[:600]


def _task_output_kind(tool: dict, sub: str = "") -> str:
    """Decide what a successful task must produce, from the tool's schema.

    Returns 'file' | 'directory' | 'stdout'. Uses the registry's `outputs`
    contract when present; a declared file/dir output param is the target, and
    tools with no output param are stdout-only (exit 0 + output is the bar).
    """
    outs = (tool.get("outputs") or {}).get(sub, {}) if sub else (tool.get("outputs") or {})
    if not isinstance(outs, dict):
        outs = {}
    if sub and not outs:
        # subcommand output contract lives on the subcommand itself
        # (discovery_to_registry stores it in subcommand_details[sub].outputs),
        # so bqtools_encode's file output is validated as a FILE, not stdout.
        detail = (tool.get("subcommand_details") or {}).get(sub) or {}
        sub_outs = detail.get("outputs") or {}
        if isinstance(sub_outs, dict):
            outs = sub_outs
    for name, meta in outs.items():
        if name == "stdout":
            continue
        t = (meta or {}).get("type", "")
        if t == "directory":
            return "directory"
        if t in ("file", "path"):
            return "file"
    return "stdout"


def _task_output_param(tool: dict, sub: str = "") -> str:
    """The input parameter name that CARRIES the task's output path.

    Returns the canonical input key whose flag/positional the tool writes to
    (bioemu -> 'output_dir', bqtools_encode -> 'output'), or '' if the tool's
    output contract is stdout-only. The task prompt uses this name so the LLM
    passes the output path to the RIGHT parameter instead of guessing.
    """
    outs = (tool.get("outputs") or {}).get(sub, {}) if sub else (tool.get("outputs") or {})
    if not isinstance(outs, dict):
        outs = {}
    if sub and not outs:
        detail = (tool.get("subcommand_details") or {}).get(sub) or {}
        sub_outs = detail.get("outputs") or {}
        if isinstance(sub_outs, dict):
            outs = sub_outs
    for name, meta in outs.items():
        if name == "stdout":
            continue
        t = (meta or {}).get("type", "")
        if t in ("file", "path", "directory"):
            # prefer the explicit outputs[out].input link (the parameter that
            # carries the output path); fall back to the output key itself when
            # an older registry has no explicit association.
            param = (meta or {}).get("input") or name
            inputs = (tool.get("inputs") or {})
            if sub:
                detail = (tool.get("subcommand_details") or {}).get(sub) or {}
                inputs = {canonical_key(p.get("name", "")): p
                          for p in (detail.get("params") or [])}
            if param in inputs:
                return param
    return ""


